// FILE: tools/generate-clipboard-capture.mjs
// VERSION: 1.0.0
// START_MODULE_CONTRACT
//   PURPOSE: Deterministically generate tools/clipboard-capture/capture-core.browser.js from the canonical ESM capture core and enforce generated-artifact freshness on demand.
//   SCOPE: Read-only freshness check (no flags or --check), regeneration (--write), and pure render/compare helpers for tests; adaptation only - no capture, normalization, payload, metadata, filename or issue logic lives here.
//   DEPENDS: vite (transformWithEsbuild), node:fs, node:url, node:path, tools/clipboard-capture/capture-core.js (canonical source).
//   LINKS: M-044, V-M-044
//   ROLE: SCRIPT
//   MAP_MODE: LOCALS
// END_MODULE_CONTRACT
//
// START_MODULE_MAP
//   USAGE - CLI usage line printed on bad arguments.
//   CANONICAL_SOURCE - repo-relative path of the authorized ESM capture core.
//   GENERATED_ARTIFACT - repo-relative path of the generated classic artifact.
//   REPO_ROOT - repository root resolved from this file.
//   SOURCE_FILE_LABEL - repo-relative source label handed to the transform.
//   FIXED_TRANSFORM_OPTIONS - fixed esbuild options (iife + globalName, es2020, no sourcemap/minify).
//   PROLOGUE - deterministic file header with the provenance notice.
//   EPILOGUE - deterministic classic-script tail assigning the five window keys in order.
//   normalizeSourceLineEndings - LF-normalize source text in memory.
//   projectCodeBody - strip block/line comments and blank lines from the transformed body.
//   renderBrowserCore - Pure generator: canonical source text in, expected artifact text out.
//   compareArtifact - Pure freshness compare: null when fresh, else a stale/missing reason naming the artifact.
//   main - CLI entry: --check compares without writing; --write regenerates the artifact.
//   invokedAsScript - import.meta.url guard so vitest imports stay side-effect free.
// END_MODULE_MAP

import { transformWithEsbuild } from 'vite'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'

const USAGE = 'usage: node tools/generate-clipboard-capture.mjs [--check|--write]'
const CANONICAL_SOURCE = 'tools/clipboard-capture/capture-core.js'
const GENERATED_ARTIFACT = 'tools/clipboard-capture/capture-core.browser.js'
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// The label handed to the transform is a repository-relative literal, never a
// runtime path, so no machine or absolute path can leak into the output; the
// projection pass drops it again together with the other full-line comments.
const SOURCE_FILE_LABEL = CANONICAL_SOURCE

// Fixed option set. `format: 'iife'` with top-level ESM exports REQUIRES
// `globalName`, so this option is load-bearing, not stylistic. Output bytes
// are a pure function of the source text plus the pinned toolchain.
const FIXED_TRANSFORM_OPTIONS = {
  loader: 'js',
  format: 'iife',
  globalName: '__ClipboardCaptureCoreModule',
  target: 'es2020',
  sourcemap: false,
  minify: false,
  sourcefile: SOURCE_FILE_LABEL
}

const PROLOGUE = [
  '// FILE: tools/clipboard-capture/capture-core.browser.js',
  '// VERSION: 1.0.0',
  '// GENERATED FILE: generated by tools/generate-clipboard-capture.mjs from tools/clipboard-capture/capture-core.js; DO NOT EDIT BY HAND.',
  '// Regenerate with: node tools/generate-clipboard-capture.mjs --write',
  '// START_MODULE_CONTRACT',
  '//   PURPOSE: Provide the file://-safe browser-global clipboard capture core generated from the canonical ESM owner.',
  '//   SCOPE: Deterministic projection of the canonical capture rules onto globalThis.ClipboardCaptureCore for classic-script loading; adaptation only, no capture logic.',
  '//   DEPENDS: tools/clipboard-capture/capture-core.js (canonical source), tools/generate-clipboard-capture.mjs (generator), browser ClipboardEvent/DataTransfer surface or test doubles with equivalent methods.',
  '//   LINKS: M-044, V-M-044',
  '//   ROLE: SCRIPT',
  '//   MAP_MODE: LOCALS',
  '// END_MODULE_CONTRACT',
  '//',
  '// START_MODULE_MAP',
  '//   ClipboardCaptureCore - Generated five-key browser namespace; see the canonical ESM MODULE_MAP for the capture rules.',
  '// END_MODULE_MAP'
].join('\n')

// Static classic wrapper: projects exactly the five public browser keys via
// explicit key literals, in the former order. No spread, no whole-module
// assignment, no Node globals, no duplicated capture logic.
const EPILOGUE = [
  ';(() => {',
  '  const core = __ClipboardCaptureCoreModule',
  '  const {',
  '    buildCaptureRecord,',
  '    buildHistoryEnvelope,',
  '    createExportFilename,',
  '    buildIssuePacket,',
  '    buildIssueUrl',
  '  } = core',
  '  globalThis.ClipboardCaptureCore = {',
  '    buildCaptureRecord,',
  '    buildHistoryEnvelope,',
  '    createExportFilename,',
  '    buildIssuePacket,',
  '    buildIssueUrl',
  '  }',
  '})()'
].join('\n')

// Canonicalizes CRLF/CR line endings to LF in memory only; the canonical file
// on disk is never rewritten, so a Windows LF/CRLF checkout cannot stale the
// generated output.
function normalizeSourceLineEndings(sourceText) {
  return sourceText.replace(/\r\n/g, '\n').replace(/\r/g, '\n')
}

// Projection hygiene: the generated artifact carries exactly one file-local
// GRACE contract (the prologue's), so full-line comments and blank lines are
// dropped from the transformed body. Pinned to the canonical input shape:
// full-line `//` comments only, single-line string and template literals, no
// block comments; the block-comment guard is defense in depth, not a license.
function projectCodeBody(transformedCode) {
  const lines = []
  let insideBlockComment = false
  for (const line of transformedCode.split('\n')) {
    const trimmed = line.trim()
    if (insideBlockComment) {
      if (trimmed.includes('*/')) {
        insideBlockComment = false
      }
      continue
    }
    if (trimmed.startsWith('/*')) {
      if (!trimmed.includes('*/')) {
        insideBlockComment = true
      }
      continue
    }
    if (trimmed === '' || trimmed.startsWith('//')) {
      continue
    }
    lines.push(line)
  }
  return lines.join('\n')
}

// Pure generator: canonical source text -> expected artifact text.
export async function renderBrowserCore(sourceText) {
  const normalizedSource = normalizeSourceLineEndings(sourceText)
  const { code } = await transformWithEsbuild(normalizedSource, SOURCE_FILE_LABEL, FIXED_TRANSFORM_OPTIONS)
  const body = projectCodeBody(code)
  return [PROLOGUE, body, EPILOGUE].join('\n') + '\n'
}

// Pure freshness compare: null when fresh, else a reason naming the artifact.
export function compareArtifact(expectedText, actualText) {
  if (actualText === null || actualText === undefined) {
    return `stale: missing: ${GENERATED_ARTIFACT} does not exist`
  }
  if (actualText === expectedText) {
    return null
  }
  return (
    `stale: ${GENERATED_ARTIFACT} does not match the bytes generated from ${CANONICAL_SOURCE}; ` +
    'the canonical source changed without regeneration or the generated artifact was manually edited'
  )
}

async function main() {
  const args = process.argv.slice(2)
  const writeMode = args.includes('--write')
  const checkMode = args.includes('--check')
  const unknown = args.filter((arg) => arg !== '--write' && arg !== '--check')

  if (unknown.length > 0 || (writeMode && checkMode)) {
    process.stderr.write(`${USAGE}\n`)
    process.exit(2)
  }

  let expectedText
  try {
    const rawSource = readFileSync(path.join(REPO_ROOT, CANONICAL_SOURCE), 'utf8')
    expectedText = await renderBrowserCore(rawSource)
  } catch (error) {
    const message = error && error.message ? error.message : String(error)
    process.stderr.write(`error: generating ${GENERATED_ARTIFACT} failed: ${message}\n`)
    process.exit(1)
  }

  const artifactPath = path.join(REPO_ROOT, GENERATED_ARTIFACT)

  if (writeMode) {
    writeFileSync(artifactPath, expectedText, 'utf8')
    process.stdout.write(`wrote ${GENERATED_ARTIFACT} (${Buffer.byteLength(expectedText, 'utf8')} bytes)\n`)
    return
  }

  let actualText
  try {
    // Windows checkouts carry CRLF; the freshness compare is line-ending
    // insensitive (the write always emits LF bytes).
    actualText = normalizeSourceLineEndings(readFileSync(artifactPath, 'utf8'))
  } catch {
    actualText = null
  }

  const reason = compareArtifact(expectedText, actualText)
  if (reason) {
    process.stderr.write(`${reason}\nrun: node tools/generate-clipboard-capture.mjs --write\n`)
    process.exit(1)
  }
  process.stdout.write(`fresh: ${GENERATED_ARTIFACT} matches the bytes generated from ${CANONICAL_SOURCE}\n`)
}

const invokedAsScript =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href

if (invokedAsScript) {
  main().catch((error) => {
    const message = error && error.message ? error.message : String(error)
    process.stderr.write(`error: ${message}\n`)
    process.exit(1)
  })
}
