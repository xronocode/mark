/**
 * front-matter-props.spec.ts — C-24 R-8: YAML front matter opens as a
 * read-only properties table; clicking it shows the editable YAML; the
 * markdown never changes through the view. Nested YAML keeps the block.
 */

import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { installTauriShim } from './fixtures/tauri-shim'
import { bootEditor, openFileTab } from './fixtures/helpers'

const CORPUS = resolve(dirname(fileURLToPath(import.meta.url)), '../renderer/muya/fixtures/lexer-corpus')
const DOC = readFileSync(resolve(CORPUS, 'front-matter.md'), 'utf8')

async function currentMarkdown (page: Page): Promise<string> {
  return page.evaluate(() => {
    const el = document.querySelector('#app') as any
    return el?.__vue_app__?.config?.globalProperties?.$pinia?.state?.value?.editor?.currentFile?.markdown ?? ''
  })
}

test.describe('front matter properties view (C-24)', () => {
  test.beforeEach(async ({ page }) => {
    await installTauriShim(page)
  })

  test('opens as a table, click shows YAML, leaving shows the table again, markdown unchanged', async ({ page }) => {
    await bootEditor(page)
    await openFileTab(page, '/tmp/c24/fm.md', DOC)
    const table = page.locator('.ag-front-matter-table')
    await expect(table).toBeVisible({ timeout: 5_000 })
    await expect(table.locator('.ag-fm-key')).toHaveText(['title', 'author', 'tags', 'aliases', 'draft', 'version'])
    await expect(table.locator('.ag-fm-value').first()).toHaveText('Agent report: weekly')
    await expect(table.locator('.ag-fm-chip')).toHaveText(['mark', 'test', 'quoted, tag', 'weekly', 'report'])
    await expect(page.locator('pre.ag-front-matter code')).toBeHidden()
    await page.screenshot({ path: 'test-results/c24-front-matter-table.png' })

    const before = await currentMarkdown(page)
    await table.click()
    await expect(page.locator('pre.ag-front-matter code')).toBeVisible()
    await expect(page.locator('.ag-front-matter-table')).toHaveCount(0)
    await expect(page.locator('pre.ag-front-matter code')).toContainText('# generated by an agent')

    await page.locator('.editor-with-tabs p', { hasText: 'Text after front matter.' }).click()
    await expect(page.locator('.ag-front-matter-table')).toBeVisible()
    await page.waitForTimeout(300)
    expect(await currentMarkdown(page)).toBe(before)
  })

  test('nested YAML keeps the plain YAML block', async ({ page }) => {
    await bootEditor(page)
    await openFileTab(page, '/tmp/c24/nested.md', '---\nauthor:\n  name: Mark\n---\n\n# Body\n')
    await expect(page.locator('.editor-with-tabs h1')).toContainText('Body', { timeout: 5_000 })
    await expect(page.locator('.ag-front-matter-table')).toHaveCount(0)
    await expect(page.locator('pre.ag-front-matter code')).toContainText('name: Mark')
  })
})
