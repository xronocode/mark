import { describe, expect, it } from 'vitest'
import { parseFrontMatterProps } from 'muya/lib/utils/frontMatterProps'

const FALLBACKS = {
  'nested map': 'author:\n  name: Mark\n  email: m@x',
  'block scalar': 'summary: |\n  line one\n  line two',
  'folded scalar': 'summary: >\n  text',
  anchor: 'base: &b 1',
  alias: 'copy: *b',
  'flow map': 'meta: {a: 1}',
  'nested inline list': 'm: [a, [b, c]]',
  'unbalanced list': 'tags: [a, b',
  'unterminated quote': 'title: "oops',
  'indented first line': '  title: x',
  'not a mapping': 'just some text',
  empty: '   \n\n',
  'list of maps': 'items:\n  - name: a',
  'uneven list indent': 'tags:\n  - a\n    - b'
}

describe('parseFrontMatterProps', () => {
  it('reads the agent-style fixture: comments, quotes, inline and block lists, scalars', () => {
    const yaml = [
      '# generated by an agent',
      'title: "Agent report: weekly"',
      'author: Mark Bot',
      'tags: [mark, test, "quoted, tag"]',
      'aliases:',
      '  - weekly',
      "  - 'report'",
      'draft: false',
      'version: 2.3'
    ].join('\n')
    expect(parseFrontMatterProps(yaml)).toEqual([
      { key: 'title', value: 'Agent report: weekly' },
      { key: 'author', value: 'Mark Bot' },
      { key: 'tags', value: ['mark', 'test', 'quoted, tag'] },
      { key: 'aliases', value: ['weekly', 'report'] },
      { key: 'draft', value: 'false' },
      { key: 'version', value: '2.3' }
    ])
  })

  it('strips trailing comments from plain scalars only', () => {
    expect(parseFrontMatterProps('a: x # note\nb: "y # kept"')).toEqual([
      { key: 'a', value: 'x' },
      { key: 'b', value: 'y # kept' }
    ])
  })

  it('unescapes quoted scalars', () => {
    expect(parseFrontMatterProps('a: "say \\"hi\\""\nb: \'it\'\'s\'')).toEqual([
      { key: 'a', value: 'say "hi"' },
      { key: 'b', value: "it's" }
    ])
  })

  it('an empty value and an empty inline list are kept', () => {
    expect(parseFrontMatterProps('a:\nb: []')).toEqual([
      { key: 'a', value: '' },
      { key: 'b', value: [] }
    ])
  })

  it('review-1 misreads: comment-only value, escaped backslash-n, trailing comma', () => {
    expect(parseFrontMatterProps('a: #comment\nb: "x\\\\nb"\nc: "l1\\nl2"\nd: [a, b, ]')).toEqual([
      { key: 'a', value: '' },
      { key: 'b', value: 'x\\nb' },
      { key: 'c', value: 'l1\nl2' },
      { key: 'd', value: ['a', 'b'] }
    ])
  })

  it('keeps URLs and colons inside plain values', () => {
    expect(parseFrontMatterProps('link: https://example.com/a?b=c')).toEqual([
      { key: 'link', value: 'https://example.com/a?b=c' }
    ])
  })

  for (const [name, yaml] of Object.entries(FALLBACKS)) {
    it(`falls back to the YAML block for ${name}`, () => {
      expect(parseFrontMatterProps(yaml)).toBeNull()
    })
  }
})
