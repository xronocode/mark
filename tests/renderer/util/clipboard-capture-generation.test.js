import { describe, expect, it, vi } from 'vitest'
import { spawnSync } from 'node:child_process'
import { readFileSync, statSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { renderBrowserCore, compareArtifact } from '../../../tools/generate-clipboard-capture.mjs'
import * as esmCore from '../../../tools/clipboard-capture/capture-core.js'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const canonicalPath = resolve(repoRoot, 'tools/clipboard-capture/capture-core.js')
const artifactPath = resolve(repoRoot, 'tools/clipboard-capture/capture-core.browser.js')

const BROWSER_KEYS = [
  'buildCaptureRecord',
  'buildHistoryEnvelope',
  'createExportFilename',
  'buildIssuePacket',
  'buildIssueUrl'
]

const ESM_EXPORT_NAMES = [
  'TOOL_SCHEMA_VERSION',
  'HISTORY_SCHEMA_VERSION',
  'KNOWN_TEXT_TYPES',
  'normalizeLineEndings',
  'buildCaptureRecord',
  'buildHistoryEnvelope',
  'createExportFilename',
  'buildIssuePacket',
  'buildIssueUrl'
]

const GENERATED_NOTICE =
  'generated by tools/generate-clipboard-capture.mjs from tools/clipboard-capture/capture-core.js; DO NOT EDIT BY HAND'

function createDataTransfer({ types = [], dataByType = {}, items = [], files = [] } = {}) {
  return {
    types,
    items,
    files,
    getData(type) {
      return dataByType[type] ?? ''
    }
  }
}

function withPinnedRealm(run) {
  const pinnedIso = '2026-05-24T18:42:13.000Z'
  const pinnedMs = new Date(pinnedIso).getTime()
  const fixedUuid = 'e611084f-3c33-4c1f-a450-4d38e4a5ffa0'
  const cryptoDescriptor = Object.getOwnPropertyDescriptor(globalThis, 'crypto')
  vi.useFakeTimers({ now: pinnedMs, toFake: ['Date'] })
  Object.defineProperty(globalThis, 'crypto', {
    value: { randomUUID: () => fixedUuid },
    configurable: true,
    writable: true
  })
  try {
    return run({ pinnedIso, fixedUuid })
  } finally {
    vi.useRealTimers()
    if (cryptoDescriptor) {
      Object.defineProperty(globalThis, 'crypto', cryptoDescriptor)
    } else {
      delete globalThis.crypto
    }
  }
}

function executeBrowserArtifact(artifactText) {
  delete globalThis.ClipboardCaptureCore
  new Function(artifactText)()
  return globalThis.ClipboardCaptureCore
}

describe('clipboard-capture-generation (C-CLIPBOARD-CAPTURE-SINGLE-SOURCE)', () => {
  it('the committed artifact is fresh: node tools/generate-clipboard-capture.mjs --check exits 0 and writes nothing', async () => {
    const mtimeBefore = statSync(artifactPath).mtimeMs
    const bytesBefore = readFileSync(artifactPath, 'utf8')

    const result = spawnSync(
      process.execPath,
      ['tools/generate-clipboard-capture.mjs', '--check'],
      { cwd: repoRoot, encoding: 'utf8' }
    )
    const output = `${result.stdout}\n${result.stderr}`
    expect(result.status, output).toBe(0)
    expect(output).toContain('tools/clipboard-capture/capture-core.browser.js')

    const mtimeAfter = statSync(artifactPath).mtimeMs
    const bytesAfter = readFileSync(artifactPath, 'utf8')
    expect(mtimeAfter).toBe(mtimeBefore)
    expect(bytesAfter).toBe(bytesBefore)
  }, 120_000)

  it('generation is deterministic: two renders of the same source produce identical bytes', async () => {
    const sourceText = readFileSync(canonicalPath, 'utf8')
    const first = await renderBrowserCore(sourceText)
    const second = await renderBrowserCore(sourceText)
    expect(first).toBe(second)
    expect(second.endsWith('\n')).toBe(true)
  }, 120_000)

  it('LF and CRLF source variants generate byte-identical output', async () => {
    const sourceText = readFileSync(canonicalPath, 'utf8')
    const lfOutput = await renderBrowserCore(sourceText)
    const crlfVariant = sourceText.replace(/\n/g, '\r\n')
    const crlfOutput = await renderBrowserCore(crlfVariant)
    expect(crlfOutput).toBe(lfOutput)
  }, 120_000)

  it('the generated text carries the provenance notice and no timestamps, machine paths, source maps, eval or runtime module statements', async () => {
    const sourceText = readFileSync(canonicalPath, 'utf8')
    const output = await renderBrowserCore(sourceText)
    expect(output).toContain(GENERATED_NOTICE)
    expect(output).toMatch(/START_MODULE_CONTRACT/)
    expect(output).toMatch(/END_MODULE_CONTRACT/)
    expect(output).not.toMatch(/\d{4}-\d{2}-\d{2}T\d{2}:/)
    expect(output).not.toContain(repoRoot)
    expect(output).not.toContain(homedir())
    expect(output).not.toMatch(/sourceMappingURL/)
    expect(output).not.toMatch(/^\/\/# /m)
    expect(output).not.toMatch(/\beval\s*\(/)
    expect(output).not.toMatch(/(^|\n)\s*(import|export)[\s{(*"']/)
  }, 120_000)

  it('drift controls fail closed on inert strings: mutated source, truncated, manually edited and missing artifacts each get a stale reason', async () => {
    const sourceText = readFileSync(canonicalPath, 'utf8')
    const fresh = await renderBrowserCore(sourceText)
    expect(compareArtifact(fresh, fresh)).toBe(null)

    const mutatedSource = sourceText.replace('export const KNOWN_TEXT_TYPES', 'export const KNOWN_TEXT_TYPES_RENAMED')
    const mutatedOutput = await renderBrowserCore(mutatedSource)
    expect(mutatedOutput).not.toBe(fresh)
    expect(compareArtifact(fresh, mutatedOutput)).toContain(
      'tools/clipboard-capture/capture-core.browser.js'
    )
    expect(compareArtifact(fresh, mutatedOutput)).toMatch(/stale/)

    const truncated = fresh.slice(0, fresh.length - 8)
    expect(compareArtifact(fresh, truncated)).toMatch(/stale/)

    const manuallyEdited = fresh.replace('DO NOT EDIT BY HAND', 'EDITED BY HAND')
    expect(compareArtifact(fresh, manuallyEdited)).toMatch(/stale/)

    expect(compareArtifact(fresh, null)).toMatch(/missing/)

    // All drift inputs above are inert in-memory strings; no tracked canonical
    // or generated file is edited to simulate drift, so the real-tree freshness
    // gate above remains the only check that touches disk.
    expect(readFileSync(canonicalPath, 'utf8')).toContain('export const TOOL_SCHEMA_VERSION')
  }, 120_000)

  it('re-executing the committed classic script defines the five-key browser namespace in the former order', () => {
    const artifactText = readFileSync(artifactPath, 'utf8')
    const browserCore = executeBrowserArtifact(artifactText)
    expect(Object.keys(browserCore)).toEqual(BROWSER_KEYS)
    for (const key of BROWSER_KEYS) {
      expect(typeof browserCore[key]).toBe('function')
    }
    expect(Object.keys(browserCore)).not.toContain('TOOL_SCHEMA_VERSION')
    expect(Object.keys(browserCore)).not.toContain('normalizeLineEndings')
    delete globalThis.ClipboardCaptureCore
  })

  it('generated-versus-ESM parity: every browser export matches its ESM counterpart on a shared pinned input', () => {
    const artifactText = readFileSync(artifactPath, 'utf8')
    withPinnedRealm(({ pinnedIso, fixedUuid }) => {
      const dataTransfer = createDataTransfer({
        types: ['text/plain', 'text/html', 'text/x-markdown', 'vscode-editor-data'],
        dataByType: {
          'text/plain': 'plain\r\nbody',
          'text/html': '<p>rich</p>',
          'text/x-markdown': '- `item`',
          'vscode-editor-data': '{"version":1}'
        }
      })
      const recordInput = {
        dataTransfer,
        sourceLabel: 'parity-check',
        note: 'generated artifact parity',
        platformMeta: {
          userAgent: 'parity-agent',
          platform: 'Win32',
          language: 'en-US',
          languages: ['en-US'],
          timeZone: 'UTC',
          href: 'file:///tool/index.html'
        }
      }

      const browserCore = executeBrowserArtifact(artifactText)
      const browserRecord = browserCore.buildCaptureRecord(recordInput)
      const esmRecord = esmCore.buildCaptureRecord(recordInput)
      expect(browserRecord).toEqual(esmRecord)
      expect(esmRecord.captureId).toBe(fixedUuid)
      expect(esmRecord.capturedAt).toBe(pinnedIso)
      expect(Object.keys(browserRecord.payloads.text)).toEqual([
        'text/x-markdown',
        'text/html',
        'text/plain',
        'vscode-editor-data'
      ])

      const captures = [browserRecord, esmRecord]
      const browserEnvelope = browserCore.buildHistoryEnvelope(captures)
      const esmEnvelope = esmCore.buildHistoryEnvelope(captures)
      expect(browserEnvelope).toEqual(esmEnvelope)
      expect(esmEnvelope.exportedAt).toBe(pinnedIso)

      const browserFilename = browserCore.createExportFilename(browserRecord)
      const esmFilename = esmCore.createExportFilename(esmRecord)
      expect(browserFilename).toBe(esmFilename)
      expect(browserFilename).toBe('clipboard-parity-check-20260524-184213.json')

      const browserPacket = browserCore.buildIssuePacket(browserRecord)
      const esmPacket = esmCore.buildIssuePacket(esmRecord)
      expect(browserPacket).toBe(esmPacket)
      expect(browserPacket).toContain('# Clipboard fixture packet')
      expect(browserPacket).toContain('## Full fixture JSON')

      const urlInput = { repo: 'xronocode/mark', record: browserRecord, copiedFullPacket: true }
      const browserUrl = browserCore.buildIssueUrl(urlInput)
      const esmUrl = esmCore.buildIssueUrl({ repo: 'xronocode/mark', record: esmRecord, copiedFullPacket: true })
      expect(browserUrl).toBe(esmUrl)
      expect(browserUrl.startsWith('https://github.com/xronocode/mark/issues/new?')).toBe(true)

      expect(Object.keys(esmCore).sort()).toEqual([...ESM_EXPORT_NAMES].sort())
      expect(Object.keys(browserCore)).toEqual(BROWSER_KEYS)
    })
    delete globalThis.ClipboardCaptureCore
  })
})
